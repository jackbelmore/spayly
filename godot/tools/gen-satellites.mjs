#!/usr/bin/env node
// Emit godot/Spayly.Sim/Satellites.g.cs from src/sim/satellites.ts, so the C# table can never drift from the web one
// by a transcription slip. satellites.ts is itself generated (scripts/fetch-ephemeris.mjs): a plain data module whose
// only TypeScript is the import line and two type annotations, so stripping those leaves JavaScript that vm can run.
//
// Numbers go through Number.prototype.toString(), the shortest string that round-trips, which .NET's double parser
// reads back to the same bits. Any field this script does not know about is an error, not a silent drop.
//
// Usage: node godot/tools/gen-satellites.mjs   (writes the file; run twice and diff to check it is deterministic)
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
const srcPath = resolve(root, 'src/sim/satellites.ts')
const outPath = resolve(root, 'godot/Spayly.Sim/Satellites.g.cs')

const ts = readFileSync(srcPath, 'utf8')
const js = ts
  .replace(/^import\s[^\n]*\n/gm, '')
  .replace(/^export const (\w+)\s*:\s*[\w[\]<>, ]+=/gm, 'const $1 =')
if (/^\s*(import|export)\b/m.test(js)) throw new Error('satellites.ts has an import/export this script does not strip')
const ctx = vm.createContext({})
vm.runInContext(`${js}\n;globalThis.__out = { SATELLITES, MINOR_BODIES }`, ctx, { filename: srcPath })
const { SATELLITES, MINOR_BODIES } = ctx.__out

const pascal = (k) => k[0].toUpperCase() + k.slice(1)

function num(x) {
  if (typeof x !== 'number') throw new Error(`expected a number, got ${JSON.stringify(x)}`)
  if (Number.isNaN(x)) return 'double.NaN'
  if (x === Infinity) return 'double.PositiveInfinity'
  if (x === -Infinity) return 'double.NegativeInfinity'
  if (Object.is(x, -0)) return '-0.0'
  const s = x.toString()
  // An integer-looking literal is an int or long in C#, and one past long's range does not compile; `d` makes every
  // integer literal beyond int a double parsed from the same digits.
  return /^-?\d+$/.test(s) && Math.abs(x) > 2147483647 ? `${s}d` : s
}
const str = (s) => {
  if (typeof s !== 'string') throw new Error(`expected a string, got ${JSON.stringify(s)}`)
  return JSON.stringify(s)
}
const bool = (b) => {
  if (typeof b !== 'boolean') throw new Error(`expected a boolean, got ${JSON.stringify(b)}`)
  return String(b)
}
const enumOf = (type, values) => (v) => {
  if (!values.includes(v)) throw new Error(`${type}: unexpected ${JSON.stringify(v)}`)
  return `${type}.${pascal(v)}`
}
const surface = enumOf('Surface', ['rock', 'ice', 'gas', 'star', 'lava'])
const frame = enumOf('SatelliteFrame', ['ecliptic', 'pole'])
const minorKind = enumOf('BodyKind', ['planet', 'asteroid'])

/** Object initialiser from a schema of field -> formatter; unknown fields throw. */
function init(type, obj, schema, rename = {}) {
  for (const k of Object.keys(obj)) if (!(k in schema)) throw new Error(`${type}: unknown field ${k} in ${JSON.stringify(obj)}`)
  const parts = Object.entries(obj).map(([k, v]) => `${rename[k] ?? pascal(k)} = ${schema[k](v)}`)
  return `new ${type} { ${parts.join(', ')} }`
}

const ring = (r) => {
  for (const k of Object.keys(r)) if (!['inner', 'outer', 'texture'].includes(k)) throw new Error(`ring: unknown field ${k}`)
  return `new RingVisual(${num(r.inner)}, ${num(r.outer)}${r.texture !== undefined ? `, ${str(r.texture)}` : ''})`
}
const visual = (v) => init('BodyVisual', v, {
  color: str, texture: str, night: str, clouds: str, normal: str, specular: str, ring, fillGaps: bool, tint: str,
  roll: num, albedo: num, baselineTemp: num,
  atmosphere: () => { throw new Error('visual.atmosphere in satellites.ts: extend gen-satellites.mjs') },
})
const rotation = (r) => {
  for (const k of Object.keys(r)) if (!['poleRA', 'poleDec', 'W0', 'rate'].includes(k)) throw new Error(`rotation: unknown field ${k}`)
  return `new Rotation(PoleRA: ${num(r.poleRA)}, PoleDec: ${num(r.poleDec)}, W0: ${num(r.W0)}, Rate: ${num(r.rate)})`
}

const satSchema = {
  id: str, name: str, primaryId: str, frame, poleRA: num, poleDec: num, epochJD: num, a: num, e: num, incl: num, node: num,
  peri: num, M: num, periodDays: num, nodeYr: num, apsisYr: num, mass: num, radius: num, surface, locked: bool, visual,
}
const minorSchema = {
  id: str, name: str, kind: minorKind, surface, epochJD: num, a: num, e: num, incl: num, node: num, peri: num, M: num,
  nDegPerDay: num, mass: num, radius: num, rotation, rotationPeriodHours: num, visual,
}
const rename = { epochJD: 'EpochJd' }

const rows = (list, type, schema) => list.map((o) => `        ${init(type, o, schema, rename)},`).join('\n')

const out = `// GENERATED by godot/tools/gen-satellites.mjs from src/sim/satellites.ts — do not edit
//
// Satellite mean elements and GM/radius: JPL Solar System Dynamics,
//   https://ssd.jpl.nasa.gov/sats/elem/ and https://ssd.jpl.nasa.gov/sats/phys_par/
// Dwarf-planet and asteroid elements: JPL Small-Body Database, https://ssd-api.jpl.nasa.gov/doc/sbdb.html
// Both are US Government works and in the public domain.
//
// Frame says what the angles are referred to: Ecliptic is ecliptic J2000; Pole is the plane normal to (PoleRA,
// PoleDec) — JPL's local Laplace plane, or the planet's IAU equator when the table says "equatorial", in which case the
// pole comes from Catalog. In both cases the node is measured from the ascending node of that plane on the ICRF equator.
namespace Spayly.Sim;

/// <summary>The generated tables of src/sim/satellites.ts (a class named Satellites could not hold a member of that name).</summary>
public static class SatelliteTable
{
    /// <summary>The ${SATELLITES.length} moons, in the TS order.</summary>
    public static readonly IReadOnlyList<SatelliteElements> Satellites =
    [
${rows(SATELLITES, 'SatelliteElements', satSchema)}
    ];

    /// <summary>The ${MINOR_BODIES.length} dwarf planets and asteroids, in the TS order.</summary>
    public static readonly IReadOnlyList<MinorBodyElements> MinorBodies =
    [
${rows(MINOR_BODIES, 'MinorBodyElements', minorSchema)}
    ];
}
`
writeFileSync(outPath, out)
console.log(`wrote ${outPath}: ${SATELLITES.length} satellites, ${MINOR_BODIES.length} minor bodies`)
